export function translateKey(
  entries: TranslationEntry[],
  key: string,
  lang: Language,
  fallback?: string
): string {
  const found = entries.find((e) => e.key === key);
  if (!found) return fallback || key;
  return found[lang] || found.en || fallback || key;
}
